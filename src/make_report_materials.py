"""Generate report_materials/evidence_pack.md: a factual evidence pack for the report.

The assignment requires the report to be written by the student, so this file is
NOT a report. It collects the measured facts, tables, figure paths, verbatim
answers and source quotes the student needs for each of the four report areas.
Every number is read from saved experiment outputs.

Usage (from the project root):
    python -m src.make_report_materials
"""
import json

import pandas as pd

from . import config

R = config.RESULTS_DIR
OUT = config.PROJECT_ROOT / "report_materials" / "evidence_pack.md"
CASES = ["KT-02", "EX-05", "DS-02", "NG-06", "SY-03", "DS-05"]


def j(path):
    return json.loads(path.read_text())


def main():
    chunks = {c["chunk_id"]: c for c in j(config.CHUNKS_JSON)["chunks"]}
    qs = {q["query_id"]: q for q in j(config.DATA_DIR / "evaluation" / "questions.json")["questions"]}
    ret = j(R / "stress_test" / "retrieval_results.json")
    rows = {r["query_id"]: r for r in ret["questions"]}
    gen = j(R / "stress_test" / "generation_results.json")["cases"]
    rep = j(R / "stress_test" / "stress_test_report.json")
    review = {c["query_id"]: c["manual_review"] for c in rep["generation_cases"]}
    lat = j(R / "latency" / "latency_summary.json")
    tab = {t["key"]: t for t in lat["table"]}
    o = ret["overall"]
    L = []
    w = L.append

    w("# Evidence pack (facts only, not a report)\n")
    w("Generated by `src/make_report_materials.py` from saved experiment outputs. Use it as source "
      "material: the report must be written in your own words. Numbers are copied from "
      "`results/`; figures are in `results/figures/`.\n")

    # ------------------------------------------------------------------ 1
    w("## 1. Architecture: Bi-Encoder vs Cross-Encoder (facts from this project)\n")
    w(f"- **Bi-Encoder:** `{config.BI_ENCODER_NAME}`.")
    w("  - Query and chunk are encoded **separately** into 384-dimensional vectors, then L2-normalised.")
    w("  - Relevance = inner product = cosine similarity (FAISS `IndexFlatIP`).")
    w(f"- **Cross-Encoder:** `{config.CROSS_ENCODER_NAME}`.")
    w("  - Each (query, chunk) pair is fed **together** as one input, so self-attention spans both texts.")
    w("  - Output: one unbounded relevance logit per pair.")
    emb = lat["scaling"]["bi_encoder_corpus_embedding"]
    w("- **Measured on this machine:**")
    w(f"  - Embedding all {emb['n_chunks']} chunks once (offline, cached): {emb['median']:.0f} ms "
      f"(≈ {emb['per_chunk_ms']:.1f} ms per chunk).")
    w(f"  - Embedding one query: {tab['query_embed_ms']['median']:.1f} ms (median).")
    w(f"  - FAISS search: {tab['faiss_search_ms']['median']:.3f} ms.")
    w(f"  - Cross-Encoder on 10 pairs: {tab['ce_score_ms']['median']:.0f} ms (median).")
    w("  - Nothing can be cached for the Cross-Encoder, because each pair depends on the query.")
    w("- **Score scales differ:**")
    w("  - Cosine similarities in our top-10 lists lie between "
      f"{min(c['cosine_score'] for r in ret['questions'] for c in r['candidates']):.3f} and "
      f"{max(c['cosine_score'] for r in ret['questions'] for c in r['candidates']):.3f}.")
    w(f"  - Cross-Encoder logits lie between "
      f"{min(c['ce_score'] for r in ret['questions'] for c in r['candidates']):.2f} and "
      f"{max(c['ce_score'] for r in ret['questions'] for c in r['candidates']):.2f}.")
    w("  - Only rank orders are comparable.")
    k = rows["KT-02"]
    w("\n**Worked example (KT-02, keyword trap): the same 10 candidates under both scorers**\n")
    df = pd.DataFrame(k["candidates"]).sort_values("baseline_rank")
    df["text"] = df.chunk_id.map(lambda c: chunks[c]["text"][:70].replace("\n", " ").replace("|", "/"))
    w("| baseline rank | re-ranked rank | chunk | cosine | CE logit | relevant | distractor | text |")
    w("|---|---|---|---|---|---|---|---|")
    for r in df.itertuples():
        w(f"| {r.baseline_rank} | {r.reranked_rank} | {r.chunk_id} | {r.cosine_score:.3f} | {r.ce_score:.2f} | "
          f"{'yes' if r.relevant else ''} | {'yes' if r.distractor else ''} | {r.text} |")
    w(f"\nQuestion: *{qs['KT-02']['question']}*\n")

    # ------------------------------------------------------------------ 2
    w("## 2. Failure cases, rank shifts, Answer 1 vs Answer 2\n")
    w(f"**Retrieval over the {o['n_questions']} verified questions:**\n")
    w("| | Recall@3 | Hit@3 | MRR@10 | Evidence coverage@3 |\n|---|---|---|---|---|")
    for p in ("baseline", "reranked"):
        # mean of the per-question values: the stored overall means are rounded to 4 dp,
        # and rounding them again to 3 dp can be off by one in the last digit
        qs_ = ret["questions"]
        m = {k: sum(q[p][k] for q in qs_) / len(qs_) for k in ("recall@3", "hit@3", "mrr@10", "evidence_cov@3")}
        w(f"| {p} | {m['recall@3']:.3f} | {m['hit@3']:.3f} | {m['mrr@10']:.3f} | {m['evidence_cov@3']:.3f} |")
    w(f"\n- **Shared top-10 pool:** Recall@10 = {o['recall@10']:.3f}.")
    w(f"- **Chunks moved:** {o['relevant_chunks_promoted_4to10_into_top3']} relevant chunks were promoted "
      f"from ranks 4-10 into the top-3, and {o['relevant_chunks_demoted_from_top3']} were demoted out of it.")
    w(f"- **Per-question outcome:** improved {len(o['improved'])}, unchanged {len(o['unchanged'])}, "
      f"worsened {len(o['worsened'])}.")
    w(f"  - Top-3 evidence actually changed only for: improved {o['improved_top3_coverage']}, "
      f"worsened {o['worsened_top3_coverage']}. The rest are rank-only moves.")
    w(f"- **Confirmed rescues:** {o['rescues']}.")
    w(f"  - Strict rescues (the baseline top-3 had no relevant chunk at all): {o['strict_rescues']}.")
    w("  - NG-06 (negation) was added after a retrieval-only screen of 24 negation phrasings; 3 met the rank "
      "criterion and 2 were rejected on checking. All 24 are in `results/stress_test/negation_screen.json`.")
    w("- **Per-category table:** `results/tables/recall_summary.md`.")
    w("- **Figures:**")
    w("  - `results/figures/recall_at3_by_category.png`")
    w("  - `results/figures/outcome_counts_by_category.png`")
    w("  - `results/figures/rank_shifts_relevant_chunks.png`")
    w("  - `results/figures/top10_before_after.png`\n")
    for qid in CASES:
        q, r, g, rv = qs[qid], rows[qid], gen[qid], review[qid]
        kind = ("strict rescue" if r["strict_rescue"] else "rescue") if r["rescue"] else "regression"
        w(f"### {qid} ({q['category']}, {kind})\n")
        w(f"**Question:** {q['question']}\n")
        w(f"**Verified reference answer:** {q['reference_answer']}\n")
        w("**Source evidence (verbatim, PDF page):**\n")
        for e in q["evidence"]:
            w(f"- p. {', '.join(map(str, e['pages']))}, chunk {e['chunk_ids']}: \"{e['quote']}\"")
        if q["distractors"]:
            w("\n**Known distractor passage(s):**\n")
            for d in q["distractors"]:
                w(f"- p. {', '.join(map(str, d['pages']))}, chunk {d['chunk_ids']}: \"{d['quote']}\"")
        when = "written after the retrieval screen" if qid == "NG-06" else "recorded before measuring"
        w(f"\n**Why it is hard ({when}):** {q['difficulty_reason']}\n")
        w("**Rank shifts of the relevant chunks:** " + "; ".join(
            f"chunk {s['chunk_id']} #{s['baseline_rank']} → #{s['reranked_rank']}" for s in r["relevant_rank_shifts"]))
        w(f"\n**Top-3:** baseline {r['baseline']['top3']} → re-ranked {r['reranked']['top3']}. "
          f"Evidence coverage {r['baseline']['evidence_cov@3']:.2f} → {r['reranked']['evidence_cov@3']:.2f}.\n")
        w("| chunk | pages | in baseline top-3 | in re-ranked top-3 | first words |\n|---|---|---|---|---|")
        for cid in dict.fromkeys(r["baseline"]["top3"] + r["reranked"]["top3"]):
            c = chunks[cid]
            w(f"| {cid}{' (relevant)' if cid in q['relevant_chunk_ids'] else ''} | {c['page_start']}-{c['page_end']} | "
              f"{'yes' if cid in r['baseline']['top3'] else ''} | {'yes' if cid in r['reranked']['top3'] else ''} | "
              f"{c['text'][:80].replace(chr(10), ' ').replace('|', '/')} |")
        w(f"\n**Answer 1 (baseline), manual verdict: {rv['answer_1_verdict']}**\n")
        w("> " + g["answer_1"].replace("\n", "\n> "))
        w(f"\n**Answer 2 (re-ranked), manual verdict: {rv['answer_2_verdict']}**\n")
        w("> " + g["answer_2"].replace("\n", "\n> "))
        w("\n**Review notes:**\n")
        w(f"- Answer 1: {rv['answer_1_notes']}")
        w(f"- Answer 2: {rv['answer_2_notes']}")
        w(f"- Missing clauses: A1 {rv['missing_clauses']['answer_1'] or 'none'}; A2 {rv['missing_clauses']['answer_2'] or 'none'}")
        w(f"- Unsupported claims: A1 {rv['unsupported_claims']['answer_1'] or 'none found'}; "
          f"A2 {rv['unsupported_claims']['answer_2'] or 'none found'}")
        cit = rv["citation_issues"]["answer_1"] + rv["citation_issues"]["answer_2"]
        w(f"- Citation issues: {cit or 'none'}")
        w(f"- **Answer change: {rv['answer_change']}**\n")
    w("### Repeated generation (5 runs per pipeline per case, Vertex AI)\n")
    w("| Case | Answer 1 verdicts | Answer 2 verdicts | A1 all key facts | A2 all key facts |\n|---|---|---|---|---|")
    for r in rep["repeat_runs"]["cases"]:
        fmt = lambda v: ", ".join(f"{k} ×{n}" for k, n in v.items())
        w(f"| {r['query_id']} | {fmt(r['answer_1_verdicts'])} | {fmt(r['answer_2_verdicts'])} | "
          f"{r['answer_1_all_key_facts']}/{r['n_runs']} | {r['answer_2_all_key_facts']}/{r['n_runs']} |")
    w("\n- Verdicts were assigned after reading all 60 answers; the key-fact columns are an automatic regex check.")
    w("- Notes per case:")
    for r in rep["repeat_runs"]["cases"]:
        w(f"  - **{r['query_id']}:** {r['notes']}")
    w("")
    w("### Failures re-ranking could not fix (no rescue possible)\n")
    for x in rep["limitations"]:
        if x.startswith(("C-04", "DS-01")):
            w(f"- {x}")
    w(f"- Relevant chunk not in the top-10 at all for: {o['questions_with_no_relevant_in_top10']}.\n")

    # ------------------------------------------------------------------ 3
    w("## 3. Latency profiling (measured)\n")
    hw = lat["hardware"]
    w("- **Hardware and software:**")
    w(f"  - {hw['cpu']}, {hw['logical_cpus']} logical CPUs, PyTorch with {hw['torch_threads']} threads, "
      f"{hw['ram_gb']} GB RAM, GPU: {hw['gpu']}.")
    w(f"  - torch {hw['torch']}, faiss {hw['faiss']}, sentence-transformers {hw['sentence_transformers']}.")
    w("- **Method:**")
    w("  - Every step timed with `time.perf_counter()`, after warm-up; model loading and indexing excluded.")
    w("  - One shared retrieval per repetition.")
    w(f"  - {lat['retrieval_questions']} questions × {lat['repeats']} repeats on the retrieval side.")
    ga = lat["generation_attempts"]
    w(f"  - Gemini: {ga['completed_paired_runs']} paired runs via {ga['backend'][0]}.")
    w(f"- **Gemini API attempts:** {ga['api_attempts_total']} in total, {ga['api_attempts_ok']} succeeded and "
      f"{ga['api_attempts_failed']} failed. Failed attempts are logged and excluded from the measurements.\n")
    w("| Component | n | mean ms | median ms | std ms | p95 ms |\n|---|---|---|---|---|---|")
    for t in lat["table"]:
        w(f"| {t['component']} | {t['n']} | {t['mean']:.3f} | {t['median']:.3f} | {t['std']:.3f} | {t['p95']:.3f} |")
    w("\n- **Re-ranking cost:**")
    w(f"  - Additional re-ranking time (Cross-Encoder + sort): {lat['rerank_overhead_mean_ms']:.1f} ms (mean).")
    w(f"  - Retrieval-side slowdown: {lat['retrieval_slowdown_mean_ratio']:.1f}x (mean), "
      f"{lat['retrieval_slowdown_median_ratio']:.1f}x (median).")
    w("- **End-to-end:**")
    w(f"  - P2/P1 = {lat['end_to_end_slowdown_median_ratio']:.2f}x (median), "
      f"{lat['end_to_end_slowdown_mean_ratio']:.2f}x (mean). Both are dominated by Gemini's run-to-run variance "
      f"(Answer 2 std {tab['gen2_ms']['std'] / 1000:.1f} s), not by re-ranking.")
    w(f"  - Re-ranking is {lat['rerank_share_of_p2_end_to_end']:.1%} of P2's mean end-to-end time.")
    t = lat["tokens"]
    w(f"- **Tokens per answer (median):**")
    w(f"  - Answer 1: {t['answer1_input']['median']:.0f} in / {t['answer1_output']['median']:.0f} out / "
      f"{t['answer1_thinking']['median']:.0f} thinking.")
    w(f"  - Answer 2: {t['answer2_input']['median']:.0f} / {t['answer2_output']['median']:.0f} / "
      f"{t['answer2_thinking']['median']:.0f}.")
    ce = lat["cost_estimate_usd"]
    w(f"- **Cost estimate:** ≈ ${ce['estimated_cost_usd']:.3f} for {ce['successful_calls']} answers "
      f"(list prices {ce['prices_per_1M_usd']} per 1M tokens; an estimate).")
    w("- **Figures:**")
    w("  - `results/figures/latency_breakdown.png`")
    w("  - `results/figures/latency_comparison.png`")
    w("- **Full write-up of the method:** `results/latency/latency_analysis.md`.\n")

    # ------------------------------------------------------------------ 4
    w("## 4. Scaling (measured + clearly marked extrapolation)\n")
    sc = lat["scaling"]
    w("| Cross-Encoder pairs scored per query | median ms |\n|---|---|")
    for n, v in sc["cross_encoder_vs_pairs_ms"].items():
        w(f"| {n}{' (= whole corpus)' if n == '85' else ''} | {v['median']:.1f} |")
    fit = sc["cross_encoder_linear_fit_ms"]
    w(f"\nLinear fit: {fit['per_pair']:.1f} ms per pair. **Extrapolation (not measured):**\n")
    w("| corpus size | Cross-Encoder over every chunk, per query |\n|---|---|")
    for n, v in sc["cross_encoder_full_corpus_extrapolation_ms"].items():
        w(f"| {int(n):,} chunks | ≈ {v / 1000:,.0f} s |")
    w("\n| FAISS exact search, index size | median ms |\n|---|---|")
    for n, v in sc["faiss_vs_index_size_ms"].items():
        w(f"| {n} | {v['median']:.3f} |")
    w("\n- **Two-stage cost at 100k chunks:** query embedding (measured median "
      f"{tab['query_embed_ms']['median']:.1f} ms) + FAISS search (synthetic 100k: "
      f"{sc['faiss_vs_index_size_ms']['100000 (synthetic)']['median']:.1f} ms) + re-ranking 10 candidates "
      f"(measured {tab['ce_score_ms']['median']:.0f} ms).")
    w("- **Figure:** `results/figures/latency_scaling.png`.\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(config.PROJECT_ROOT)} ({len(L)} lines)")


if __name__ == "__main__":
    main()
